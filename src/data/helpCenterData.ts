function normalizeArabicForMatch(text: string): string {
  return (text || '')
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[“”"«»؟?,،.!:\-•]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export interface SmartGuideAnswerResult {
  answer: string;
  matchedSectionTitle?: string;
  matchedSectionId?: string;
  matchedQuestion?: string;
  relatedQuestions: string[];
}

export function resolveLocalSmartGuideAnswer(userQuery: string): SmartGuideAnswerResult {
  const normQuery = normalizeArabicForMatch(userQuery);
  const queryTokens = normQuery.split(' ').filter((w) => w.length >= 2);

  if (!normQuery) {
    return {
      answer:
        'مرحبًا بك في “المرشد الذكي” لمنصة جذوري. يمكنني إجابتك فورًا على أي استفسار يخص خطوات التسجيل، السجل الأساسي، عمود النسب، صلاحيات أمين السجل، منهجية التحقيق، أو الباقات والسياسات المعتمدة.',
      relatedQuestions: SMART_GUIDE_STARTER_QUESTIONS.slice(0, 4),
    };
  }

  let bestScore = 0;
  let bestSection: HelpCenterSection | null = null;
  let bestFaq: HelpCenterFaqItem | null = null;
  const secondaryMatches: Array<{ section: HelpCenterSection; faq: HelpCenterFaqItem; score: number }> = [];

  for (const section of HELP_CENTER_SECTIONS) {
    const normSecTitle = normalizeArabicForMatch(section.title);
    const normSecContent = normalizeArabicForMatch(section.content || '');

    for (const faq of section.faqs) {
      const normQ = normalizeArabicForMatch(faq.q);
      const normA = normalizeArabicForMatch(faq.a);
      const normKw = normalizeArabicForMatch((faq.keywords || []).join(' '));

      let score = 0;
      if (normQ === normQuery) score += 100;
      else if (normQ.includes(normQuery) || normQuery.includes(normQ)) score += 60;

      for (const token of queryTokens) {
        if (normQ.includes(token)) score += 14;
        if (normKw.includes(token)) score += 12;
        if (normSecTitle.includes(token)) score += 8;
        if (normA.includes(token)) score += 5;
        if (normSecContent.includes(token)) score += 3;
      }

      if (score > bestScore) {
        if (bestFaq && bestSection && bestScore > 15) {
          secondaryMatches.push({ section: bestSection, faq: bestFaq, score: bestScore });
        }
        bestScore = score;
        bestSection = section;
        bestFaq = faq;
      } else if (score > 15) {
        secondaryMatches.push({ section, faq, score });
      }
    }
  }

  secondaryMatches.sort((a, b) => b.score - a.score);

  if (bestFaq && bestSection && bestScore >= 12) {
    const related = secondaryMatches
      .slice(0, 3)
      .map((m) => m.faq.q)
      .filter((q) => q !== bestFaq!.q);

    return {
      answer: `${bestFaq.a}\n\n— المصدر الإرشادي: قسم «${bestSection.title}» في الدليل الإرشادي لمنصة جذوري.`,
      matchedSectionTitle: bestSection.title,
      matchedSectionId: bestSection.id,
      matchedQuestion: bestFaq.q,
      relatedQuestions:
        related.length > 0
          ? related
          : SMART_GUIDE_STARTER_QUESTIONS.filter((q) => q !== bestFaq!.q).slice(0, 3),
    };
  }

  return {
    answer:
      'شكرًا لاستفسارك. يعتمد “المرشد الذكي” في منصة جذوري على الدليل الإرشادي الرسمي والعقود والسياسات المعتمدة:\n\n• إذا كان سؤالك يتعلق بـ **بدء البحث وتوثيق عمود النسب**: يبدأ الفحص الأولي مجانًا عبر إدخال الاسم الثلاثي واسم العائلة والدولة في الصفحة الرئيسية.\n• إذا كان سؤالك يتعلق بـ **بناء شجرة العائلة وإضافة الأفراد**: تتاح “نافذة الإدراج العائلي” بعد تفعيل الخدمة واعتماد صفة “أمين السجل”.\n• إذا كانت لديك **مشجرة عائلية أو حالة بحثية خاصة**: يمكنك إرسال تذكرة مباشرة لفريق التحقيق عبر نموذج التواصل في هذه الصفحة.\n\nتنبيه مهم: لا يُعد “المرشد الذكي” بديلًا عن العقود أو السياسات أو فريق البحث المختص.',
    matchedSectionTitle: 'الدعم والتواصل',
    matchedSectionId: 'support-and-contact',
    relatedQuestions: SMART_GUIDE_STARTER_QUESTIONS.slice(0, 4),
  };
}
