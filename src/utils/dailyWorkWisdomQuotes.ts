/**
 * Generates an exact 365-item library of distinct Arabic wisdom quotes
 * celebrating work, diligence, sincerity, mastery, and perseverance.
 */
export const DAILY_WORK_WISDOM_QUOTES_365: string[] = (() => {
  const list: string[] = [...BASE_WISDOM_QUOTES];
  for (let i = 0; i < VIRTUE_OPENINGS.length; i++) {
    for (let j = 0; j < VIRTUE_COMPLEMENTS.length; j++) {
      if (list.length >= 365) break;
      const combined = `إن ${VIRTUE_OPENINGS[i]} ${VIRTUE_COMPLEMENTS[j]}`;
      if (!list.includes(combined)) {
        list.push(combined);
      }
    }
    if (list.length >= 365) break;
  }
  return list.slice(0, 365);
})();

const WISDOM_LOGIN_COUNTER_KEY = 'juthori_team_wisdom_login_counter_v1';
const WISDOM_SESSION_MARK_KEY = 'juthori_team_wisdom_session_marked_v1';

/**
 * Returns the 0-indexed day of the year (0..364)
 */
export function getDayOfYearIndex(date: Date = new Date()): number {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff =
    date.getTime() -
    start.getTime() +
    (start.getTimezoneOffset() - date.getTimezoneOffset()) * 60 * 1000;
  const oneDay = 1000 * 60 * 60 * 24;
  const day = Math.floor(diff / oneDay);
  return Math.max(0, (day - 1) % DAILY_WORK_WISDOM_QUOTES_365.length);
}

/**
 * Increments the login quote counter in localStorage so every login displays a fresh quote.
 */
export function incrementWisdomLoginCounter(): number {
  if (typeof window === 'undefined') return 0;
  try {
    const raw = localStorage.getItem(WISDOM_LOGIN_COUNTER_KEY);
    const current = raw ? parseInt(raw, 10) || 0 : 0;
    const next = current + 1;
    localStorage.setItem(WISDOM_LOGIN_COUNTER_KEY, String(next));
    sessionStorage.setItem(WISDOM_SESSION_MARK_KEY, '1');
    return next;
  } catch {
    return 0;
  }
}

/**
 * Reads (and initializes per-session) the login quote counter.
 */
export function getOrAdvanceSessionWisdomCounter(): number {
  if (typeof window === 'undefined') return 0;
  try {
    const alreadyMarked = sessionStorage.getItem(WISDOM_SESSION_MARK_KEY);
    const raw = localStorage.getItem(WISDOM_LOGIN_COUNTER_KEY);
    const current = raw ? parseInt(raw, 10) || 0 : 0;
    if (!alreadyMarked) {
      const next = current + 1;
      localStorage.setItem(WISDOM_LOGIN_COUNTER_KEY, String(next));
      sessionStorage.setItem(WISDOM_SESSION_MARK_KEY, '1');
      return next;
    }
    return current;
  } catch {
    return 0;
  }
}

/**
 * Selects a quote from the 365-quote library combining the day of the year (1..365)
 * and the login counter so that it rotates daily across the year AND changes on every login.
 */
export function getDailyAndLoginWisdomQuote(loginCounterOffset: number = 0): {
  quote: string;
  quoteNumber: number;
  totalQuotes: number;
} {
  const totalQuotes = DAILY_WORK_WISDOM_QUOTES_365.length;
  const dayIndex = getDayOfYearIndex();
  const combinedIndex =
    (((dayIndex + loginCounterOffset) % totalQuotes) + totalQuotes) % totalQuotes;
  return {
    quote: DAILY_WORK_WISDOM_QUOTES_365[combinedIndex],
    quoteNumber: combinedIndex + 1,
    totalQuotes,
  };
}
